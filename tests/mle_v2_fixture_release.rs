/// The signer-independent exit cross-bindings `ChannelSettlementManager._checkCloseProof` and
/// `CloseFundingMaterializer` enforce on chain: the close intent's `intmax_state_root` is the
/// `close_` lifecycle's finalized root, and the whole-vector backing statement carries the close
/// intent's exact `(channel, settled_tx_chain, token_funds_digest)` key, that same finalized
/// commitment and the lifecycle's last block as its anchor.
fn validate_close_backing_binding(
    close: &CloseIntentDescriptor,
    close_lifecycle: &LifecycleDescriptor,
) -> Result<(), String> {
    let backing = CloseAssetBackingPublicInputs::from_u64_slice(&parse_full_public_inputs(
        "close_asset_backing_mle.json",
    )?)
    .map_err(|e| e.to_string())?;
    require_equal(
        &close.channel_fund_intmax_state_root,
        &close_lifecycle.final_state_root,
        "close_intent.channel_fund_intmax_state_root vs close_lifecycle.final_state_root",
    )?;
    require_equal(
        &backing.channel_id.channel_id(),
        &close.channel_id,
        "backing.channel_id vs close_intent.channel_id",
    )?;
    require_equal(
        &backing.settled_tx_chain,
        &close.final_settled_tx_chain,
        "backing.settled_tx_chain vs close_intent.final_settled_tx_chain",
    )?;
    require_equal(
        &backing.token_funds_digest,
        &close.token_funds_digest,
        "backing.token_funds_digest vs close_intent.token_funds_digest",
    )?;
    require_equal(
        &backing.finalized_extended_state_commitment,
        &close_lifecycle.final_state_root,
        "backing.finalized_extended_state_commitment vs close_lifecycle.final_state_root",
    )?;
    let last_block = close_lifecycle
        .blocks
        .last()
        .ok_or_else(|| "close_lifecycle.json has no blocks".to_owned())?;
    require_equal(
        &backing.anchor_block_number.as_u64(),
        &last_block.block_number,
        "backing.anchor_block_number vs close_lifecycle last block",
    )
}

