fn parse_full_public_inputs(name: &str) -> Result<Vec<u64>, String> {
    // Artifact-class/schema/config/compact integrity is enforced independently by
    // `tracked_live_full_v2_fixtures_are_exhaustive_and_match_configs`. Read just this redundant
    // view here so companion relationship failures remain visible even during an intentional
    // wire-generation cutover, instead of being masked by the first stale full-proof schema.
    json_value(name)?
        .pointer("/proof/publicInputs")
        .and_then(serde_json::Value::as_array)
        .ok_or_else(|| format!("{name}: missing proof.publicInputs array"))?
        .iter()
        .enumerate()
        .map(|(i, value)| {
            let encoded = value
                .as_str()
                .ok_or_else(|| format!("{name}: publicInputs[{i}] must be a hex string"))?;
            let hex = encoded
                .strip_prefix("0x")
                .ok_or_else(|| format!("{name}: publicInputs[{i}] lacks canonical 0x prefix"))?;
            if hex.len() != 16 || hex.bytes().any(|b| b.is_ascii_uppercase()) {
                return Err(format!(
                    "{name}: publicInputs[{i}] is not canonical fixed-width lowercase hex"
                ));
            }
            u64::from_str_radix(hex, 16)
                .map_err(|e| format!("{name}: publicInputs[{i}] is not canonical u64: {e}"))
        })
        .collect()
}

fn require_equal<T: PartialEq + std::fmt::Debug>(
    actual: &T,
    expected: &T,
    what: &str,
) -> Result<(), String> {
    if actual == expected {
        Ok(())
    } else {
        Err(format!(
            "{what} mismatch: actual={actual:?}, expected={expected:?}"
        ))
    }
}

fn validity_public_inputs(value: &VpiDescriptor) -> Result<ValidityPublicInputs, String> {
    Ok(ValidityPublicInputs {
        initial_block_number: BlockNumber::new(value.initial_block_number)
            .map_err(|e| e.to_string())?,
        initial_block_chain: value.initial_block_chain,
        initial_ext_commitment: value.initial_ext_commitment,
        final_block_number: BlockNumber::new(value.final_block_number)
            .map_err(|e| e.to_string())?,
        final_block_chain: value.final_block_chain,
        final_ext_commitment: value.final_ext_commitment,
        prover: value.prover,
    })
}

fn validate_validity_proof_binding(value: &VpiDescriptor, full_name: &str) -> Result<(), String> {
    let actual = parse_full_public_inputs(full_name)?;
    let expected = validity_public_inputs(value)?.hash().to_u64_vec();
    require_equal(
        &actual,
        &expected,
        &format!("{full_name} validity public-input hash"),
    )
}

fn validate_withdrawal_proof_binding(
    payout: &PayoutDescriptor,
    full_name: &str,
) -> Result<(), String> {
    let mut withdrawal_hash = Bytes32::default();
    for withdrawal in &payout.withdrawals {
        withdrawal_hash = Withdrawal {
            recipient: withdrawal.recipient,
            token_index: withdrawal.token_index,
            amount: withdrawal.amount,
            nullifier: withdrawal.nullifier,
            aux_data: withdrawal.aux_data,
        }
        .hash_with_prev_hash(withdrawal_hash);
    }
    let block_number = BlockNumber::new(payout.block_number).map_err(|e| e.to_string())?;
    let inputs = WithdrawalProofPublicInputs {
        withdrawal_hash,
        withdrawal_prover: payout.withdrawal_prover,
        ext_public_state_commitment: payout.ext_commitment,
        block_number,
    };
    let expected = [
        inputs.hash().to_u64_vec(),
        inputs.ext_public_state_commitment.to_u64_vec(),
        inputs.block_number.to_u64_vec(),
    ]
    .concat();
    let actual = parse_full_public_inputs(full_name)?;
    require_equal(
        &actual,
        &expected,
        &format!("{full_name} withdrawal public inputs"),
    )
}

fn padded_member_commitment(member_pk_gs: &[Bytes32]) -> Result<Bytes32, String> {
    if member_pk_gs.is_empty() || member_pk_gs.len() > MAX_SIG_CLUSTER {
        return Err(format!(
            "member count {} is outside 1..={MAX_SIG_CLUSTER}",
            member_pk_gs.len()
        ));
    }
    let mut padded = [Bytes32::default(); MAX_SIG_CLUSTER];
    padded[..member_pk_gs.len()].copy_from_slice(member_pk_gs);
    Ok(close_member_set_commitment(
        &padded,
        u8::try_from(member_pk_gs.len()).expect("bounded member count"),
    ))
}

fn fixed_token_vectors(
    registry: &[u32],
    amounts: &[U256],
    what: &str,
) -> Result<([u32; MAX_CHANNEL_TOKENS], [U256; MAX_CHANNEL_TOKENS]), String> {
    let registry: [u32; MAX_CHANNEL_TOKENS] = registry.try_into().map_err(|_| {
        format!("{what}.token_registry must have exactly {MAX_CHANNEL_TOKENS} entries")
    })?;
    let amounts: [U256; MAX_CHANNEL_TOKENS] = amounts.try_into().map_err(|_| {
        format!("{what}.channel_fund_amounts must have exactly {MAX_CHANNEL_TOKENS} entries")
    })?;
    Ok((registry, amounts))
}

