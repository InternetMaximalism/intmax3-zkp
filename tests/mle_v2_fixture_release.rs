fn validate_lifecycle_pair(
    lifecycle_name: &str,
    validity_full_name: &str,
    payout_name: &str,
    withdrawal_full_name: &str,
    require_close_family_amounts: bool,
) -> Result<(), String> {
    let lifecycle: LifecycleDescriptor =
        strict_value(lifecycle_name, &json_value(lifecycle_name)?)?;
    let payout: PayoutDescriptor = strict_value(payout_name, &json_value(payout_name)?)?;
    validate_lifecycle_shape(&lifecycle, lifecycle_name)?;
    validate_payout_shape(&payout, payout_name)?;
    validate_validity_proof_binding(&lifecycle.vpis, validity_full_name)?;
    validate_withdrawal_proof_binding(&payout, withdrawal_full_name)?;
    require_equal(
        &payout.block_number,
        &lifecycle.vpis.final_block_number,
        &format!("{payout_name} block_number"),
    )?;
    require_equal(
        &payout.ext_commitment,
        &lifecycle.vpis.final_ext_commitment,
        &format!("{payout_name} ext_commitment"),
    )?;
    let withdrawal = &payout.withdrawals[0];
    if withdrawal.amount > lifecycle.deposit.amount {
        return Err(format!(
            "{payout_name}: withdrawal amount {} exceeds lifecycle deposit {}",
            withdrawal.amount, lifecycle.deposit.amount
        ));
    }
    if require_close_family_amounts {
        // Signer-independent exit: the close intent's fund vector is what REMAINS in the channel
        // after the lifecycle's sole native withdrawal (`deposit - withdrawal`), and
        // `CloseLifecycleE2E` requires the L1 payout pulled by the Manager to equal exactly that
        // materialized amount (`finalizedChannelFundAmount(0) == amounts[0]`). The co-generator
        // therefore fixes `deposit - withdrawal == withdrawal` (6 / 3); a different pair is a
        // stale or hand-edited close family.
        if withdrawal.amount == U256::default() {
            return Err(format!("{payout_name}: the close family needs a nonzero withdrawal"));
        }
        require_equal(
            &(lifecycle.deposit.amount - withdrawal.amount),
            &withdrawal.amount,
            "close_ remaining channel funds (deposit - withdrawal) vs payout",
        )?;
    }
    Ok(())
}

