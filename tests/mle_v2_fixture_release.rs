//!
//! Heavy statement E2Es prove and verify the circuits. This gate protects the artifact boundary:
//! exact full/config schemas, canonical JSON, full↔config identity, compact decode/re-encode
//! uniqueness, redundant ABI-view agreement, and submission/Proof-DA metadata over the exact
//! compact bytes. It deliberately scans the directory as well as using a manifest so adding a new
//! live `*_mle.json` cannot silently escape the release gate.

