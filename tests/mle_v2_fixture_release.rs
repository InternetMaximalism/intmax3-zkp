fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn data_path(name: &str) -> PathBuf {
    repo_root().join("contracts/test/data").join(name)
}

fn read(name: &str) -> String {
    let path = data_path(name);
    fs::read_to_string(&path).unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()))
}

fn parse_config(name: &str) -> MleVerifierV2ConfigFixture {
    MleVerifierV2ConfigFixture::from_canonical_json(&read(name))
        .unwrap_or_else(|e| panic!("{name} is not a strict canonical proof-free V2 config: {e}"))
}

