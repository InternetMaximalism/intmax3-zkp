#[derive(Debug)]
struct CohortSets {
    configs: BTreeSet<String>,
    full_proofs: BTreeSet<String>,
    companions: BTreeSet<String>,
}

fn insert_unique(
    set: &mut BTreeSet<String>,
    name: &str,
    invocation: &str,
    class: &str,
) -> Result<(), String> {
    if !set.insert(name.to_owned()) {
        return Err(format!(
            "{name} is owned more than once in the {class} manifest (second owner: {invocation})"
        ));
    }
    Ok(())
}

fn generator_cohort_sets() -> Result<CohortSets, String> {
    let mut sets = CohortSets {
        configs: BTreeSet::new(),
        full_proofs: BTreeSet::new(),
        companions: BTreeSet::new(),
    };
    for cohort in GENERATOR_COHORTS {
        for name in cohort.configs {
            insert_unique(&mut sets.configs, name, cohort.invocation, "config")?;
        }
        for name in cohort.full_proofs {
            insert_unique(&mut sets.full_proofs, name, cohort.invocation, "full proof")?;
        }
        for name in cohort.companions {
            insert_unique(&mut sets.companions, name, cohort.invocation, "companion")?;
        }
    }

    for name in &sets.configs {
        if sets.full_proofs.contains(name) || sets.companions.contains(name) {
            return Err(format!("{name} appears in multiple artifact classes"));
        }
    }
    for name in &sets.full_proofs {
        if sets.companions.contains(name) {
            return Err(format!("{name} appears in multiple artifact classes"));
        }
    }
    Ok(sets)
}

fn exact_set(
    actual: &BTreeSet<String>,
    expected: &BTreeSet<String>,
    label: &str,
) -> Result<(), String> {
    let missing = expected.difference(actual).cloned().collect::<Vec<_>>();
    let extra = actual.difference(expected).cloned().collect::<Vec<_>>();
    if missing.is_empty() && extra.is_empty() {
        Ok(())
    } else {
        Err(format!(
            "{label} mismatch; missing={missing:?}, unexpected={extra:?}"
        ))
    }
}

fn regular_file_names(path: &std::path::Path) -> Result<BTreeSet<String>, String> {
    fs::read_dir(path)
        .map_err(|error| format!("cannot read {}: {error}", path.display()))?
        .map(|entry| {
            let entry = entry.map_err(|error| format!("cannot read directory entry: {error}"))?;
            if !entry
                .file_type()
                .map_err(|error| format!("cannot inspect {}: {error}", entry.path().display()))?
                .is_file()
            {
                return Err(format!(
                    "unexpected non-file artifact in tracked directory: {}",
                    entry.path().display()
                ));
            }
            entry
                .file_name()
                .into_string()
                .map_err(|_| format!("non-UTF-8 artifact name in {}", path.display()))
        })
        .collect()
}

fn json_value(name: &str) -> Result<serde_json::Value, String> {
    serde_json::from_str(&read(name)).map_err(|e| format!("{name}: invalid JSON: {e}"))
}

fn strict_value<T: serde::de::DeserializeOwned>(
    name: &str,
    value: &serde_json::Value,
) -> Result<T, String> {
    serde_json::from_value(value.clone())
        .map_err(|e| format!("{name}: strict companion schema mismatch: {e}"))
}

fn nonzero_address(value: Address, what: &str) -> Result<(), String> {
    if value == Address::default() {
        Err(format!("{what} must not be the zero address"))
    } else {
        Ok(())
    }
}

fn nonzero_word(value: Bytes32, what: &str) -> Result<(), String> {
    if value == Bytes32::default() {
        Err(format!("{what} must not be zero"))
    } else {
        Ok(())
    }
}

fn validate_registration(value: &RegistrationDescriptor, what: &str) -> Result<(), String> {
    let count = value.member_pk_gs.len();
    if count == 0 || count > MAX_SIG_CLUSTER {
        return Err(format!(
            "{what}.member_pk_gs length {count} is outside 1..={MAX_SIG_CLUSTER}"
        ));
    }
    for (field, actual) in [
        ("member_pk_bs", value.member_pk_bs.len()),
        ("regev_pk_digests", value.regev_pk_digests.len()),
        ("recipients", value.recipients.len()),
    ] {
        if actual != count {
            return Err(format!(
                "{what}.{field} length {actual} != member_pk_gs length {count}"
            ));
        }
    }
    if usize::from(value.bp_member_slot) >= count {
        return Err(format!("{what}.bp_member_slot is outside the active set"));
    }
    if value.channel_id == 0 {
        return Err(format!("{what}.channel_id must be nonzero"));
    }
    for (i, recipient) in value.recipients.iter().copied().enumerate() {
        nonzero_address(recipient, &format!("{what}.recipients[{i}]"))?;
    }
    Ok(())
}

fn validate_deposit(value: &DepositDescriptor, what: &str) -> Result<(), String> {
    nonzero_address(value.depositor, &format!("{what}.depositor"))?;
    nonzero_word(value.recipient, &format!("{what}.recipient"))?;
    if value.amount == U256::zero() {
        return Err(format!("{what}.amount must be nonzero"));
    }
    // Token zero and zero aux-data are canonical for the native fixture and intentionally valid.
    let _ = (value.token_index, value.aux_data);
    Ok(())
}

fn validate_blocks(values: &[BlockDescriptor], what: &str) -> Result<(), String> {
    if values.is_empty() {
        return Err(format!("{what}.blocks must not be empty"));
    }
    for (i, block) in values.iter().enumerate() {
        let expected_number = u64::try_from(i + 1).expect("fixture block count fits u64");
        if block.block_number != expected_number {
            return Err(format!(
                "{what}.blocks[{i}].block_number {} != contiguous {expected_number}",
                block.block_number
            ));
        }
        if block.key_ids.is_empty() {
            return Err(format!("{what}.blocks[{i}].key_ids must not be empty"));
        }
        let _ = (block.channel_id, block.timestamp, block.tx_tree_root);
    }
    Ok(())
}

fn validate_vpi_shape(value: &VpiDescriptor, what: &str) -> Result<(), String> {
    if value.final_block_number <= value.initial_block_number {
        return Err(format!("{what}: final block must advance"));
    }
    nonzero_word(
        value.initial_ext_commitment,
        &format!("{what}.initial_ext_commitment"),
    )?;
    nonzero_word(
        value.final_ext_commitment,
        &format!("{what}.final_ext_commitment"),
    )?;
    Ok(())
}

fn validate_lifecycle_shape(value: &LifecycleDescriptor, what: &str) -> Result<(), String> {
    validate_registration(&value.registration, &format!("{what}.registration"))?;
    validate_deposit(&value.deposit, &format!("{what}.deposit"))?;
    validate_blocks(&value.blocks, what)?;
    validate_vpi_shape(&value.vpis, &format!("{what}.vpis"))?;
    if value.genesis_state_root != value.vpis.initial_ext_commitment
        || value.final_state_root != value.vpis.final_ext_commitment
    {
        return Err(format!(
            "{what}: lifecycle roots do not equal the validity initial/final commitments"
        ));
    }
    if value.blocks.last().expect("nonempty").block_number != value.vpis.final_block_number {
        return Err(format!(
            "{what}: last block number does not equal validity final block"
        ));
    }
    nonzero_word(value.proof_hash, &format!("{what}.proof_hash"))?;
    if value.proof_length == 0 {
        return Err(format!("{what}.proof_length must be nonzero"));
    }
    Ok(())
}

fn validate_c2c_lifecycle_shape(value: &C2cLifecycleDescriptor, what: &str) -> Result<(), String> {
    validate_registration(&value.registration1, &format!("{what}.registration1"))?;
    validate_registration(&value.registration2, &format!("{what}.registration2"))?;
    if value.registration1.channel_id == value.registration2.channel_id {
        return Err(format!("{what}: the two registrations alias one channel"));
    }
    validate_deposit(&value.deposit, &format!("{what}.deposit"))?;
    validate_blocks(&value.blocks, what)?;
    validate_vpi_shape(&value.vpis, &format!("{what}.vpis"))?;
    if value.genesis_state_root != value.vpis.initial_ext_commitment
        || value.final_state_root != value.vpis.final_ext_commitment
    {
        return Err(format!(
            "{what}: lifecycle roots do not equal the validity initial/final commitments"
        ));
    }
    if value.blocks.last().expect("nonempty").block_number != value.vpis.final_block_number {
        return Err(format!(
            "{what}: last block number does not equal validity final block"
        ));
    }
    nonzero_word(value.proof_hash, &format!("{what}.proof_hash"))?;
    if value.proof_length == 0 {
        return Err(format!("{what}.proof_length must be nonzero"));
    }
    Ok(())
}

fn validate_payout_shape(value: &PayoutDescriptor, what: &str) -> Result<(), String> {
    if value.withdrawals.len() != 1 {
        return Err(format!(
            "{what}.withdrawals must contain the generator's exact one-withdrawal cohort"
        ));
    }
    nonzero_address(
        value.withdrawal_prover,
        &format!("{what}.withdrawal_prover"),
    )?;
    nonzero_word(value.ext_commitment, &format!("{what}.ext_commitment"))?;
    for (i, withdrawal) in value.withdrawals.iter().enumerate() {
        nonzero_address(
            withdrawal.recipient,
            &format!("{what}.withdrawals[{i}].recipient"),
        )?;
        nonzero_word(
            withdrawal.nullifier,
            &format!("{what}.withdrawals[{i}].nullifier"),
        )?;
        if withdrawal.amount == U256::zero() {
            return Err(format!("{what}.withdrawals[{i}].amount must be nonzero"));
        }
        let _ = (withdrawal.token_index, withdrawal.aux_data);
    }
    Ok(())
}

fn validate_companion_schema(name: &str, value: &serde_json::Value) -> Result<(), String> {
    match name {
        "vpi_fixture.json" => {
            let parsed: VpiDescriptor = strict_value(name, value)?;
            validate_vpi_shape(&parsed, name)
        }
        "block_fixture.json" => {
            let parsed: StandaloneBlockDescriptor = strict_value(name, value)?;
            nonzero_word(
                parsed.genesis_state_root,
                "block_fixture.genesis_state_root",
            )?;
            nonzero_word(parsed.final_state_root, "block_fixture.final_state_root")?;
            nonzero_word(parsed.proof_hash, "block_fixture.proof_hash")?;
            if parsed.proof_length == 0
                || parsed.final_block_number <= parsed.initial_block_number
                || parsed.key_ids.is_empty()
            {
                return Err("block_fixture.json: invalid block/proof dimensions".to_owned());
            }
            let _ = (
                parsed.channel_id,
                parsed.timestamp,
                parsed.tx_tree_root,
                parsed.block_deposit_hash_chain,
                parsed.block_channel_reg_hash_chain,
                parsed.initial_block_chain,
                parsed.final_block_chain,
            );
            Ok(())
        }
        "lifecycle.json"
        | "close_lifecycle.json"
        | "sepolia_lifecycle.json"
        | "burn_lifecycle.json" => {
            let parsed: LifecycleDescriptor = strict_value(name, value)?;
            validate_lifecycle_shape(&parsed, name)
        }
        "c2c_lifecycle.json" => {
            let parsed: C2cLifecycleDescriptor = strict_value(name, value)?;
            validate_c2c_lifecycle_shape(&parsed, name)
        }
        "withdrawal_payout.json"
        | "close_withdrawal_payout.json"
        | "sepolia_withdrawal_payout.json"
        | "burn_withdrawal_payout.json"
        | "c2c_withdrawal_payout.json" => {
            let parsed: PayoutDescriptor = strict_value(name, value)?;
            validate_payout_shape(&parsed, name)
        }
        "close_intent.json" => {
            let parsed: CloseIntentDescriptor = strict_value(name, value)?;
            if parsed.member_pk_gs.is_empty()
                || parsed.channel_fund_amounts.len() != MAX_CHANNEL_TOKENS
                || parsed.token_registry.len() != MAX_CHANNEL_TOKENS
                || parsed.token_count == 0
                || usize::from(parsed.token_count) > MAX_CHANNEL_TOKENS
            {
                return Err("close_intent.json: invalid fixed-width companion arrays".to_owned());
            }
            Ok(())
        }
        "withdrawal_claim.json" => {
            let parsed: WithdrawalClaimDescriptor = strict_value(name, value)?;
            nonzero_address(parsed.recipient, "withdrawal_claim.recipient")?;
            nonzero_word(
                parsed.withdrawal_nullifier,
                "withdrawal_claim.withdrawal_nullifier",
            )
        }
        "post_close_claim.json" => {
            let parsed: PostCloseClaimDescriptor = strict_value(name, value)?;
            nonzero_address(parsed.recipient, "post_close_claim.recipient")?;
            nonzero_word(
                parsed.shared_native_nullifier,
                "post_close_claim.shared_native_nullifier",
            )
        }
        "cancel_close.json" => {
            let parsed: CancelCloseDescriptor = strict_value(name, value)?;
            if parsed.member_pk_gs.is_empty() || parsed.member_pk_gs.len() > MAX_SIG_CLUSTER {
                return Err("cancel_close.json: invalid member_pk_gs length".to_owned());
            }
            Ok(())
        }
        "pw_reg.json" => {
            let parsed: PartialWithdrawalRegistrationDescriptor = strict_value(name, value)?;
            let count = usize::from(parsed.member_count);
            if count == 0
                || count > MAX_SIG_CLUSTER
                || parsed.member_pk_gs.len() != count
                || parsed.member_pk_bs.len() != count
                || parsed.regev_pk_digests.len() != count
                || parsed.recipients.len() != count
                || usize::from(parsed.bp_member_slot) >= count
            {
                return Err("pw_reg.json: inconsistent active member arrays/count".to_owned());
            }
            for (i, recipient) in parsed.recipients.iter().copied().enumerate() {
                nonzero_address(recipient, &format!("pw_reg.recipients[{i}]"))?;
            }
            Ok(())
        }
        "pw_submit.json" => {
            let parsed: PartialWithdrawalSubmitDescriptor = strict_value(name, value)?;
            nonzero_address(parsed.manager, "pw_submit.manager")?;
            nonzero_address(parsed.verifier, "pw_submit.verifier")?;
            nonzero_address(
                parsed.withdrawal_recipient,
                "pw_submit.withdrawal_recipient",
            )?;
            if parsed.channel_fund_amounts.len() != MAX_CHANNEL_TOKENS
                || parsed.token_registry.len() != MAX_CHANNEL_TOKENS
                || parsed.token_count == 0
                || usize::from(parsed.token_count) > MAX_CHANNEL_TOKENS
            {
                return Err("pw_submit.json: invalid fixed-width token arrays".to_owned());
            }
            Ok(())
        }
        "close_asset_backing_public_inputs.json" => {
            let limbs: Vec<u64> = strict_value(name, value)?;
            if limbs.len() != CLOSE_ASSET_BACKING_PUBLIC_INPUTS_LEN {
                return Err(format!(
                    "{name}: expected {CLOSE_ASSET_BACKING_PUBLIC_INPUTS_LEN} raw limbs"
                ));
            }
            CloseAssetBackingPublicInputs::from_u64_slice(&limbs).map_err(|e| e.to_string())?;
            // The bare limb file is a redundant view of the proof's own public inputs.
            require_equal(
                &limbs,
                &parse_full_public_inputs("close_asset_backing_mle.json")?,
                "close_asset_backing_public_inputs vs close_asset_backing_mle.proof.publicInputs",
            )
        }
        "close_asset_backing_manifest.json" => {
            let parsed: BackingFixtureManifest = strict_value(name, value)?;
            require_equal(
                &parsed.schema_version,
                &PUBLIC_CLOSE_BUNDLE_SCHEMA_VERSION,
                "close_asset_backing_manifest.schemaVersion",
            )?;
            require_equal(
                &parsed.backing_public_input_count,
                &CLOSE_ASSET_BACKING_PUBLIC_INPUTS_LEN,
                "close_asset_backing_manifest.backingPublicInputCount",
            )?;
            // The manifest authenticates exactly the three checked-in backing artifacts (the same
            // reader `DeployCloseCli._readBackingMle` uses for a live bundle).
            for (file, bytes, sha) in [
                (
                    "close_asset_backing_mle.json",
                    Some(parsed.backing_mle_bytes),
                    &parsed.backing_mle_sha256,
                ),
                (
                    "close_asset_backing_mle_config.json",
                    Some(parsed.backing_mle_config_bytes),
                    &parsed.backing_mle_config_sha256,
                ),
                // The limb file carries no byte count in the manifest, only its digest.
                (
                    "close_asset_backing_public_inputs.json",
                    None,
                    &parsed.backing_public_inputs_sha256,
                ),
            ] {
                let content = read(file);
                if let Some(bytes) = bytes {
                    require_equal(&content.len(), &bytes, &format!("{name}: {file} byte length"))?;
                }
                let digest = format!("0x{}", hex::encode(Sha256::digest(content.as_bytes())));
                require_equal(&digest, sha, &format!("{name}: {file} sha256"))?;
            }
            let public_inputs = CloseAssetBackingPublicInputs::from_u64_slice(
                &parse_full_public_inputs("close_asset_backing_mle.json")?,
            )
            .map_err(|e| e.to_string())?;
            require_equal(
                &public_inputs.anchor_block_number.as_u64(),
                &parsed.backing_anchor_block_number,
                "close_asset_backing_manifest.backingAnchorBlockNumber",
            )?;
            require_equal(
                &public_inputs.finalized_extended_state_commitment,
                &parsed.backing_finalized_extended_state_commitment,
                "close_asset_backing_manifest.backingFinalizedExtendedStateCommitment",
            )
        }
        _ => Err(format!("{name}: no strict companion schema is registered")),
    }
}

