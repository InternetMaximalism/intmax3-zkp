function normalizeGateArray(value, label) {
  if (!Array.isArray(value) || value.length === 0 || value.length > 255) {
    throw new Error(`${label} must contain 1..255 gate rows`);
  }
  return value.map((entry, index) => normalizeGate(entry, `${label}[${index}]`));
}

function normalizeEncodedRecord(value, encoding, label, maxBytes) {
  const record = requireObject(value, label);
  requireExactKeys(record, ['encoding', 'byteLength', 'keccak256', 'bytes'], label);
  if (record.encoding !== encoding) throw new Error(`${label}.encoding mismatch`);
  const byteLength = fixtureNumber(record.byteLength, `${label}.byteLength`);
  if (byteLength > maxBytes
      || typeof record.bytes !== 'string'
      || record.bytes.length > 2 + maxBytes * 2) {
    throw new Error(`${label} exceeds the release-reviewed byte cap`);
  }
  const encoded = canonicalBytes(record.bytes, `${label}.bytes`);
  const digest = canonicalBytes(record.keccak256, `${label}.keccak256`, 32);
  if (BigInt((encoded.length - 2) / 2) !== BigInt(byteLength)) {
    throw new Error(`${label} byte length mismatch`);
  }
  if (keccak256(encoded) !== digest) throw new Error(`${label} Keccak digest mismatch`);
  return { encoding, byteLength, keccak256: digest, bytes: encoded };
}

function normalizeCircuit(value, label) {
  const circuit = requireObject(value, label);
  requireExactKeys(circuit, [
    'degreeBits', 'numPublicInputs', 'numConstants', 'numRoutedWires', 'numWires',
    'numSelectors', 'numGateConstraints', 'quotientDegreeFactor',
  ], label);
  return {
    degreeBits: fixtureNumber(circuit.degreeBits, `${label}.degreeBits`, MAX_ROW_VARIABLES_V2),
    numPublicInputs: fixtureNumber(circuit.numPublicInputs, `${label}.numPublicInputs`, MAX_PUBLIC_INPUTS_V2),
    numConstants: fixtureNumber(circuit.numConstants, `${label}.numConstants`, MAX_CONSTITUENT_WIDTH_V2),
    numRoutedWires: fixtureNumber(circuit.numRoutedWires, `${label}.numRoutedWires`, MAX_ROUTED_WIRES_V2),
    numWires: fixtureNumber(circuit.numWires, `${label}.numWires`, MAX_CONSTITUENT_WIDTH_V2),
    numSelectors: fixtureNumber(circuit.numSelectors, `${label}.numSelectors`, 0xff),
    numGateConstraints: fixtureNumber(circuit.numGateConstraints, `${label}.numGateConstraints`, 123),
    quotientDegreeFactor: fixtureNumber(circuit.quotientDegreeFactor, `${label}.quotientDegreeFactor`, 8),
  };
}

function normalizePublicInputWireMap(value, circuit, label) {
  const wireMap = canonicalBytes(value, label, 3 * circuit.numPublicInputs);
  const raw = Buffer.from(wireMap.slice(2), 'hex');
  const degree = 2 ** circuit.degreeBits;
  for (let offset = 0; offset < raw.length; offset += 3) {
    const row = raw.readUInt16LE(offset);
    const column = raw[offset + 2];
    if (row >= degree || column >= circuit.numRoutedWires) {
      throw new Error(`${label} contains an out-of-range canonical routed wire`);
    }
  }
  return wireMap;
}

