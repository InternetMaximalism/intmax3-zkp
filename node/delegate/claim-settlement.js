function requireObject(value, label) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw new Error(`${label} must be an object`);
  return value;
}

function uintString(value, label, max = null) {
  let n;
  if (typeof value === 'string') {
    if (!/^(0|[1-9][0-9]*)$/.test(value)) {
      throw new Error(`${label} must be a canonical unsigned integer`);
    }
    if (max !== null && value.length > max.toString().length) {
      throw new Error(`${label} is out of range`);
    }
    n = BigInt(value);
  } else if (typeof value === 'number') {
    if (!Number.isSafeInteger(value) || value < 0) {
      throw new Error(`${label} must be a canonical unsigned integer`);
    }
    n = BigInt(value);
  } else if (typeof value === 'bigint') {
    n = value;
  } else {
    throw new Error(`${label} must be a canonical unsigned integer`);
  }
  if (n < 0n || (max !== null && n > max)) throw new Error(`${label} is out of range`);
  return n.toString();
}

function fixtureNumber(value, label, max = Number.MAX_SAFE_INTEGER) {
  if (typeof value !== 'number' || !Number.isSafeInteger(value) || value < 0 || value > max) {
    throw new Error(`${label} must be a canonical JSON unsigned integer`);
  }
  return value;
}

function fixtureUintString(value, label, max = UINT64_MAX) {
  if (typeof value !== 'string') throw new Error(`${label} must be a canonical decimal string`);
  return uintString(value, label, max);
}

function goldilocks(value, label) {
  if (typeof value !== 'string' || !/^0x[0-9a-f]{16}$/.test(value)) {
    throw new Error(`${label} must be a canonical lowercase 8-byte Goldilocks hex limb`);
  }
  if (BigInt(value) >= GOLDILOCKS_MODULUS) throw new Error(`${label} is outside the Goldilocks field`);
  return value;
}

function goldilocksDecimal(value, label) {
  return fixtureUintString(value, label, GOLDILOCKS_MODULUS - 1n);
}

function bytes(value, label, length) {
  const canonicalByteString = typeof value === 'string' && /^0x(?:[0-9a-fA-F]{2})*$/.test(value);
  const exactLength = length == null || (
    typeof value === 'string' && (value.length - 2) / 2 === length
  );
  if (!canonicalByteString || !exactLength || !isHexString(value, length)) {
    throw new Error(`${label} must be ${length == null ? 'hex bytes' : `${length} bytes`}`);
  }
  return String(value).toLowerCase();
}

function normalizeArray(value, label, maxLength = MAX_PUBLIC_INPUTS_V2) {
  if (!Array.isArray(value)) throw new Error(`${label} must be an array`);
  if (value.length > maxLength) throw new Error(`${label} exceeds the release-reviewed vector cap`);
  return value.map((v, i) => goldilocks(v, `${label}[${i}]`));
}

function requireExactKeys(value, expected, label) {
  const actual = Object.keys(value).sort();
  const wanted = [...expected].sort();
  if (actual.length !== wanted.length || actual.some((key, i) => key !== wanted[i])) {
    throw new Error(`${label} keys do not match the canonical MLE/WHIR v2 schema`);
  }
}

function canonicalBytes(value, label, length) {
  const normalized = bytes(value, label, length);
  if (value !== normalized) throw new Error(`${label} must use canonical lowercase 0x hex`);
  return normalized;
}

function boundedCanonicalBytes(value, label, maxBytes) {
  if (typeof value !== 'string' || value.length > 2 + maxBytes * 2) {
    throw new Error(`${label} exceeds the release-reviewed byte cap`);
  }
  return canonicalBytes(value, label);
}

function sameJson(left, right) {
  return JSON.stringify(left) === JSON.stringify(right);
}

function normalizeExt3(value, label) {
  const ext = requireObject(value, label);
  requireExactKeys(ext, ['c0', 'c1', 'c2'], label);
  return {
    c0: goldilocks(ext.c0, `${label}.c0`),
    c1: goldilocks(ext.c1, `${label}.c1`),
    c2: goldilocks(ext.c2, `${label}.c2`),
  };
}

function normalizeExt3Array(value, label, expectedLength) {
  if (!Array.isArray(value) || value.length !== expectedLength) {
    throw new Error(`${label} must contain exactly ${expectedLength} Ext3 values`);
  }
  return value.map((entry, index) => normalizeExt3(entry, `${label}[${index}]`));
}

function normalizeSumcheck(value, label, rounds, roundDegree) {
  const proof = requireObject(value, label);
  requireExactKeys(proof, ['rounds'], label);
  if (!Array.isArray(proof.rounds) || proof.rounds.length !== rounds) {
    throw new Error(`${label}.rounds must contain exactly ${rounds} rounds`);
  }
  return {
    rounds: proof.rounds.map((entry, index) => {
      const round = requireObject(entry, `${label}.rounds[${index}]`);
      requireExactKeys(round, ['nonConstant'], `${label}.rounds[${index}]`);
      return {
        nonConstant: normalizeExt3Array(
          round.nonConstant,
          `${label}.rounds[${index}].nonConstant`,
          roundDegree,
        ),
      };
    }),
  };
}

