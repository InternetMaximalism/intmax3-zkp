class CompactV2Reader {
  constructor(hex) {
    this.buffer = Buffer.from(hex.slice(2), 'hex');
    this.offset = 0;
  }

  take(length, label) {
    if (!Number.isSafeInteger(length) || length < 0 || this.offset + length > this.buffer.length) {
      throw new Error(`mleProof.compactProof.bytes is truncated while reading ${label}`);
    }
    const value = this.buffer.subarray(this.offset, this.offset + length);
    this.offset += length;
    return value;
  }

  u32(label) {
    return this.take(4, label).readUInt32LE(0);
  }

  u64(label) {
    return this.take(8, label).readBigUInt64LE(0);
  }

  base(label) {
    const value = this.u64(label);
    if (value >= GOLDILOCKS_MODULUS) {
      throw new Error(`mleProof.compactProof.bytes contains a non-canonical Goldilocks limb in ${label}`);
    }
    return `0x${value.toString(16).padStart(16, '0')}`;
  }

  baseArray(length, label) {
    return Array.from({ length }, (_, index) => this.base(`${label}[${index}]`));
  }

  ext3(label) {
    return {
      c0: this.base(`${label}.c0`),
      c1: this.base(`${label}.c1`),
      c2: this.base(`${label}.c2`),
    };
  }

  ext3Array(length, label) {
    return Array.from({ length }, (_, index) => this.ext3(`${label}[${index}]`));
  }

  root(label) {
    return `0x${this.take(32, label).toString('hex')}`;
  }

  blob(maxLength, label) {
    const length = this.u32(`${label}.length`);
    if (length > maxLength) throw new Error(`mleProof.compactProof.bytes ${label} exceeds its cap`);
    return `0x${this.take(length, label).toString('hex')}`;
  }
}

function decodeCompactProof(compactProof, shape) {
  const reader = new CompactV2Reader(compactProof);
  if (reader.take(8, 'magic').toString('hex') !== MLE_COMPACT_MAGIC_CURRENT) {
    throw new Error('mleProof.compactProof.bytes has the wrong protocol magic');
  }
  const protocolVersion = reader.u64('protocolVersion');
  const constituentWidth = reader.u32('constituentWidth');
  if (protocolVersion !== MLE_PROTOCOL_VERSION_CURRENT || constituentWidth !== shape.constituentWidth) {
    throw new Error('mleProof.compactProof.bytes protocol/width disagrees with its trusted shape');
  }
  const preprocessedLength = shape.numConstants + shape.numRoutedWires;
  const decoded = {
    protocolVersion: Number(protocolVersion),
    constituentWidth,
    circuitDigest: reader.baseArray(shape.circuitDigestLen, 'circuitDigest'),
    publicInputs: reader.baseArray(shape.publicInputsLen, 'publicInputs'),
    preprocessedRoot: reader.root('preprocessedRoot'),
    witnessRoot: reader.root('witnessRoot'),
    normInverseRoot: reader.root('normInverseRoot'),
    whirTranscript: reader.blob(shape.maxWhirNargBytes, 'whirTranscript'),
    whirHints: reader.blob(shape.maxWhirHintBytes, 'whirHints'),
    logProof: {
      rounds: Array.from({ length: shape.degreeBits }, (_, round) => ({
        nonConstant: reader.ext3Array(LOG_ROUND_DEGREE_V2, `logProof.rounds[${round}].nonConstant`),
      })),
    },
    logPreprocessed: reader.ext3Array(preprocessedLength, 'logPreprocessed'),
    logWitness: reader.ext3Array(shape.numWires, 'logWitness'),
    logNormInverse: reader.ext3Array(2 * shape.numRoutedWires, 'logNormInverse'),
    gateProof: {
      rounds: Array.from({ length: shape.degreeBits }, (_, round) => ({
        nonConstant: reader.ext3Array(shape.gateRoundDegree, `gateProof.rounds[${round}].nonConstant`),
      })),
    },
    gatePreprocessed: reader.ext3Array(preprocessedLength, 'gatePreprocessed'),
    gateWitness: reader.ext3Array(shape.numWires, 'gateWitness'),
  };
  if (reader.offset !== reader.buffer.length) {
    throw new Error('mleProof.compactProof.bytes has trailing bytes');
  }
  return decoded;
}

