function u64Le(value, label) {
  const normalized = typeof value === 'string' && /^0x[0-9a-f]{16}$/.test(value)
    ? BigInt(value)
    : BigInt(uintString(value, label, UINT64_MAX));
  const output = Buffer.alloc(8);
  output.writeBigUInt64LE(normalized);
  return output;
}

